  /// Locales passées à MaterialApp (Lingala n'a pas de délégué Material → fr).
  static List<Locale> get materialLocales {
    final codes = <String>{};
    for (final code in supportedLocales) {
      codes.add(code == 'ln' ? 'fr' : code);
    }
    return codes.map((c) => Locale(c)).toList();
  }

  /// Locale framework pour [MaterialApp.locale] (UI custom via [currentLanguage]).
  static Locale materialLocaleFor(String languageCode) {
    if (languageCode == 'ln') return const Locale('fr');
    return Locale(languageCode);
  }

