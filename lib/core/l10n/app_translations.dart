  /// Returns the translated string for [key] in the given [locale].
  /// Falls back to French, then returns the key itself if not found.
  static String translate(String key, String locale) {
    return _translations[locale]?[key] ?? _translations['fr']?[key] ?? key;
  }

  /// Résout une préférence de langue (`system` ou code explicite).
  static String resolveLanguage(String preference) {
    if (preference != 'system') return preference;
    return resolveDeviceLanguage();
  }

  /// Langue du téléphone mappée vers une locale supportée.
  static String resolveDeviceLanguage() {
    final locale = WidgetsBinding.instance.platformDispatcher.locale;
    final code = locale.languageCode.toLowerCase();
    if (supportedLocales.contains(code)) return code;

    final country = locale.countryCode?.toUpperCase();
    if (country == 'CD' || country == 'CG' || country == 'BI' || country == 'RW') {
      return 'fr';
    }
    if (country == 'KE' || country == 'TZ' || country == 'UG') {
      return 'sw';
    }
    return 'fr';
  }

